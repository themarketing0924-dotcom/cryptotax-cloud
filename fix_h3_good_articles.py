def inject_h3_after_p_start(content, search_text, h3_title):
    """Insert H3 tag before the paragraph that starts with search_text"""
    h3_tag = f'<h3 {H3}>{h3_title}</h3>\n'
    idx = content.find(search_text)
    if idx == -1:
        return content, False
    # Find the start of the <p> or <ul> or any block element before this text
    # Look backward for the nearest <p> or list start
    for start in range(idx, max(0, idx-200), -1):
        if content[start:start+2] == '<p' or content[start:start+3] == '<ul' or content[start:start+3] == '<ol':
            return content[:start] + h3_tag + content[start:], True
    # Fallback: insert right before the text
    return content[:idx] + h3_tag + content[idx:], True

def process_file(filepath, sections):
    if not os.path.exists(filepath):
        print(f'SKIP (not found): {filepath}')
        return

    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    changes = 0
    for sid, h3_pairs in sections.items():
        for search_text, h3_title in h3_pairs:
            new_content, ok = inject_h3_after_p_start(content, search_text, h3_title)
            if ok:
                content = new_content
                changes += 1
            else:
                print(f'  WARNING: not found "{search_text[:40]}" in {filepath} [{sid}]')

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f'OK ({changes} H3s): {filepath}')

if __name__ == '__main__':
    ok = 0
    for filepath, data in ARTICLES.items():
        try:
            process_file(filepath, data)
            ok += 1
        except Exception as e:
            print(f'ERROR {filepath}: {e}')
    print(f'\n완료: {ok}/{len(ARTICLES)}개 파일 처리')
