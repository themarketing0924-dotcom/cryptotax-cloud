H3_STYLE = H3

def replace_h1(content, new_h1):
    return re.sub(
        r'(<h1[^>]*>)[^<]+(</h1>)',
        lambda m: m.group(1) + new_h1 + m.group(2),
        content
    )

def replace_title(content, new_title):
    return re.sub(r'<title>[^<]+</title>', f'<title>{new_title}</title>', content)

def replace_meta(content, tag_name, new_val):
    return re.sub(
        rf'(<meta name="{tag_name}" content=")[^"]+(")',
        rf'\g<1>{new_val}\g<2>',
        content
    )

def replace_og(content, prop, new_val):
    return re.sub(
        rf'(<meta property="{prop}" content=")[^"]+(")',
        rf'\g<1>{new_val}\g<2>',
        content
    )

def replace_twitter(content, name, new_val):
    return re.sub(
        rf'(<meta name="{name}" content=")[^"]+(")',
        rf'\g<1>{new_val}\g<2>',
        content
    )

def replace_json_headline(content, new_headline):
    return re.sub(
        r'"headline":"[^"]+"',
        f'"headline":"{new_headline}"',
        content
    )

def replace_h2_and_section(content, sid, new_h2, new_body):
    """Replace H2 title and the boilerplate p-tag that follows it (stops before next H2 or CTA or adsense)."""
    # Replace H2 title
    content = re.sub(
        rf'(<h2 id="{sid}"[^>]*>)[^<]+(</h2>)',
        lambda m: m.group(1) + new_h2 + m.group(2),
        content
    )
    # Replace the boilerplate <p> right after this H2 (before calc-cta or adsense or next h2)
    content = re.sub(
        rf'(<h2 id="{sid}"[^>]*>[^<]+</h2>\s*)<p>[^<]+(?:<a[^>]*>[^<]*</a>[^<]*)*</p>',
        rf'\g<1>\n{new_body}\n',
        content,
        flags=re.DOTALL
    )
    return content

def replace_toc(content, sid, new_title):
    return re.sub(
        rf'(<a href="#{sid}">)[^<]+(</a>)',
        lambda m: m.group(1) + new_title + m.group(2),
        content
    )

def process_file(filepath, data):
    if not os.path.exists(filepath):
        print(f'SKIP (not found): {filepath}')
        return

    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    # H1
    if 'h1' in data:
        content = replace_h1(content, data['h1'])

    # title tag
    if 'title' in data:
        content = replace_title(content, data['title'])

    # meta description
    if 'desc' in data:
        content = replace_meta(content, 'description', data['desc'])
        content = replace_og(content, 'og:description', data['desc'])
        content = replace_og(content, 'og:title', data.get('title', data.get('h1', '')))
        content = replace_twitter(content, 'twitter:description', data['desc'])
        content = replace_twitter(content, 'twitter:title', data.get('title', data.get('h1', '')))
        content = replace_json_headline(content, data.get('h1', ''))

    def fmt(html):
        return html.format(h3=H3_STYLE)

    # s1
    if 's1_h2' in data and 's1' in data:
        content = replace_h2_and_section(content, 's1', data['s1_h2'], fmt(data['s1']))
        content = replace_toc(content, 's1', data['s1_h2'])

    # s2
    if 's2_h2' in data and 's2' in data:
        content = replace_h2_and_section(content, 's2', data['s2_h2'], fmt(data['s2']))
        content = replace_toc(content, 's2', data['s2_h2'])

    # s3
    if 's3_h2' in data and 's3' in data:
        content = replace_h2_and_section(content, 's3', data['s3_h2'], fmt(data['s3']))
        content = replace_toc(content, 's3', data['s3_h2'])

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)

    print(f'OK: {filepath}')

