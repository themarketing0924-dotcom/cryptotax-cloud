def process(filepath, desc, kw):
    if not os.path.exists(filepath):
        print(f'  SKIP (없음): {filepath}')
        return False

    content = open(filepath, encoding='utf-8').read()

    # 1. 메타 디스크립션 교체
    new_desc = f'<meta name="description" content="{desc}">'
    content, n_desc = re.subn(
        r'<meta\s+name="description"\s+content="[^"]*">',
        new_desc, content
    )

    # 2. keywords 태그 처리 (있으면 교체, 없으면 description 뒤에 삽입)
    new_kw = f'<meta name="keywords" content="{kw}">'
    if re.search(r'<meta\s+name="keywords"', content):
        content, n_kw = re.subn(
            r'<meta\s+name="keywords"\s+content="[^"]*">',
            new_kw, content
        )
    else:
        # description 태그 바로 뒤에 삽입
        content = re.sub(
            r'(<meta\s+name="description"\s+content="[^"]*">)',
            r'\1\n' + new_kw,
            content
        )
        n_kw = 1

    open(filepath, 'w', encoding='utf-8').write(content)
    desc_len = len(desc)
    print(f'  OK ({desc_len}자) {os.path.basename(filepath)}')
    return True

